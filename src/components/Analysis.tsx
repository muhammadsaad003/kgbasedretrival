import type { SearchResponse } from "../api";
import { aggregateConcepts, GROUP_LABEL, modalityConsensus, textModalityMatches, type ConceptGroup } from "../concepts";
import { CopyButton, formatScore, formatSeconds } from "./ui";
import { FileTextIcon, SparkIcon } from "./icons";

interface Props {
  response: SearchResponse;
  elapsedMs?: number;
  onReport: () => void;
}

export function Analysis({ response, elapsedMs, onReport }: Props) {
  const { results } = response;
  const n = results.length;
  const consensus = modalityConsensus(results);
  const agreement = textModalityMatches(response.modality, consensus);
  const stats = aggregateConcepts(results);
  const top1 = results[0]?.score;
  const mean = n ? results.reduce((sum, r) => sum + r.score, 0) / n : undefined;
  const caption = response.query_caption?.trim() ?? "";

  const groups = (["modality", "region", "view", "other"] as ConceptGroup[])
    .map((g) => ({ group: g, items: stats.filter((s) => s.concept.group === g) }))
    .filter((g) => g.items.length > 0);

  return (
    <article className="card analysis" aria-labelledby="analysis-title">
      <div className="analysis-head">
        <div className="analysis-title-group">
          <h2 id="analysis-title" className="section-title">Query analysis</h2>
          <span className="section-meta mono">answered in {formatSeconds(elapsedMs)}</span>
        </div>
        <button type="button" className="btn btn-primary btn-sm" onClick={onReport}>
          <FileTextIcon size={15} /> Generate report
        </button>
      </div>

      <div className="caption-block">
        {!response.is_dataset_image && (
          <span className="source-badge is-gen">
            <SparkIcon size={14} />
            Generated caption · BLIP-ROCO
          </span>
        )}
        <blockquote className="caption-quote">{caption || "The backend returned no caption."}</blockquote>
        <div className="caption-foot">
          {!response.is_dataset_image && (
            <p className="note">
              No exact match in the index, so the caption was generated by BLIP fine-tuned on ROCO. It is machine-generated
              and may be wrong.
            </p>
          )}
          <CopyButton text={caption} label="Copy caption" />
        </div>
      </div>

      <dl className="facts">
        <div className="fact">
          <dt>Modality · neighbour concepts</dt>
          <dd>
            {consensus ? (
              <>
                <span className="fact-value">{consensus.concept.label}</span>
                <span className="fact-sub">
                  {consensus.count}/{consensus.total} neighbours
                </span>
              </>
            ) : (
              <span className="fact-value muted">No modality concepts</span>
            )}
          </dd>
        </div>
        <div className="fact">
          <dt>Modality · caption keywords</dt>
          <dd>
            <span className={`fact-value${response.modality === "Unknown" ? " muted" : ""}`}>{response.modality || "Unknown"}</span>
            {agreement === true && <span className="tag tag-ok">agrees</span>}
            {agreement === false && <span className="tag tag-warn">disagrees</span>}
          </dd>
        </div>
        <div className="fact">
          <dt>Top-1 similarity</dt>
          <dd>
            <span className="fact-value mono">{formatScore(top1)}</span>
          </dd>
        </div>
        <div className="fact">
          <dt>Mean similarity</dt>
          <dd>
            <span className="fact-value mono">{formatScore(mean)}</span>
            <span className="fact-sub">over k = {n}</span>
          </dd>
        </div>
      </dl>

      <section className="profile" aria-labelledby="profile-title">
        <div className="profile-head">
          <h3 id="profile-title" className="subsection-title">Concept profile</h3>
          <span className="section-meta">UMLS concepts carried by the {n} retrieved neighbours</span>
        </div>
        {groups.length === 0 ? (
          <p className="note">None of the retrieved neighbours carry curated concepts.</p>
        ) : (
          <div className="profile-groups">
            {groups.map(({ group, items }) => (
              <div key={group} className="profile-group">
                <h4 className="profile-group-title">{GROUP_LABEL[group]}</h4>
                <ul className="profile-list">
                  {items.map((s) => (
                    <li key={s.concept.cui} className={`profile-row g-${s.concept.group}`} title={`${s.concept.name} (${s.concept.cui})`}>
                      <span className="profile-name">{s.concept.label}</span>
                      <span className="profile-cui mono">{s.concept.cui}</span>
                      <span className="profile-bar" aria-hidden="true">
                        <i style={{ width: `${(s.count / Math.max(1, n)) * 100}%` }} />
                      </span>
                      <span className="profile-count mono">
                        {s.count}/{n}
                      </span>
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
        )}
      </section>
    </article>
  );
}
